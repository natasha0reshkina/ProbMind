using System.Globalization;
using ProbMind.Domain.Enums;

namespace ProbMind.Infrastructure.Seeding;

public static class LargeQuestionBankSeed
{
    public static IReadOnlyList<SeedQuestionDefinition> All { get; } = Build();

    private static SeedQuestionDefinition[] Build()
    {
        var questions = ConditionalProbability()
            .Concat(Independence())
            .Concat(PValue())
            .Concat(LawLargeNumbers())
            .Concat(Randomness())
            .ToArray();

        var positions = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        return questions.Select(question =>
        {
            var position = positions.GetValueOrDefault(question.TopicCode) + 1;
            positions[question.TopicCode] = position;
            var difficulty = question.IsTransfer
                ? QuestionDifficulty.Advanced
                : DifficultyProfile(position);
            return question with { Difficulty = difficulty };
        }).ToArray();
    }

    private static IEnumerable<SeedQuestionDefinition> ConditionalProbability()
    {
        for (var i = 1; i <= 28; i++)
        {
            var prevalence = 0.02d + (i % 9) * 0.015d;
            var sensitivity = 0.72d + (i % 7) * 0.035d;
            var falsePositive = 0.025d + (i % 6) * 0.018d;
            var posterior = prevalence * sensitivity /
                            (prevalence * sensitivity + (1d - prevalence) * falsePositive);
            yield return Q(
                $"conditional_probability_large_{i:000}",
                "conditional_probability",
                Difficulty(i),
                i % 11 == 0,
                $"В выборке доля объектов класса A равна {Pct(prevalence)}. Система распознаёт A с чувствительностью {Pct(sensitivity)}, а для объекта не из A даёт положительный результат с вероятностью {Pct(falsePositive)}. У случайного объекта результат положительный. Какова вероятность, что он действительно относится к A?",
                $"По формуле Байеса: P(A|+) = P(A)P(+|A) / [P(A)P(+|A) + P(¬A)P(+|¬A)] = {Pct(posterior)}.",
                ["base_rate_neglect", "conditional_reverse"],
                [
                    O(Pct(posterior), true, null, "Верно: учтены и качество теста, и базовая частота класса."),
                    O(Pct(sensitivity), false, "conditional_reverse", "Это P(+|A), а требуется обратная условная вероятность P(A|+)."),
                    O(Pct(prevalence), false, "base_rate_neglect", "Это исходная базовая частота до получения результата теста."),
                    O(Pct(falsePositive), false, "base_rate_neglect", "Это вероятность ложноположительного результата, а не искомая апостериорная вероятность.")
                ]);
        }

        for (var i = 1; i <= 22; i++)
        {
            var shareA = 0.30d + (i % 8) * 0.05d;
            var defectA = 0.015d + (i % 6) * 0.008d;
            var defectB = 0.035d + (i % 7) * 0.011d;
            var totalDefect = shareA * defectA + (1d - shareA) * defectB;
            var posterior = shareA * defectA / totalDefect;
            yield return Q(
                $"conditional_probability_large_{i + 28:000}",
                "conditional_probability",
                Difficulty(i + 28),
                i % 9 == 0,
                $"Линия A выпускает {Pct(shareA)} продукции, линия B — остальное. Доля брака на A равна {Pct(defectA)}, на B — {Pct(defectB)}. Случайно выбранная деталь оказалась бракованной. Какова вероятность, что она произведена линией A?",
                $"P(A|брак) = P(A)P(брак|A) / P(брак), где P(брак) = {Pct(totalDefect)}. Получаем {Pct(posterior)}.",
                ["base_rate_neglect", "conditional_reverse"],
                [
                    O(Pct(posterior), true, null, "Верно: применена формула полной вероятности и затем Байес."),
                    O(Pct(shareA), false, "base_rate_neglect", "Это доля выпуска A до информации о браке."),
                    O(Pct(defectA), false, "conditional_reverse", "Это P(брак|A), а требуется P(A|брак)."),
                    O(Pct(totalDefect), false, "base_rate_neglect", "Это общая вероятность брака, то есть знаменатель формулы Байеса.")
                ]);
        }

        for (var i = 1; i <= 16; i++)
        {
            var b = 80 + i * 7;
            var both = 18 + (i * 5) % 42;
            var a = both + 30 + (i * 3) % 50;
            var total = Math.Max(240, a + b - both + 25);
            var pAgivenB = both / (double)b;
            var pBgivenA = both / (double)a;
            var pA = a / (double)total;
            var pBoth = both / (double)total;
            yield return Q(
                $"conditional_probability_large_{i + 50:000}",
                "conditional_probability",
                Difficulty(i + 50),
                i % 8 == 0,
                $"Среди {total} наблюдений событие A произошло {a} раз, событие B — {b} раз, одновременно A и B — {both} раз. Чему равно P(A|B)?",
                $"После условия B пространство сужается до {b} наблюдений. Из них A произошло {both} раз, поэтому P(A|B) = {both}/{b} = {Pct(pAgivenB)}.",
                ["conditional_reverse"],
                [
                    O(Pct(pAgivenB), true, null, "Верно: знаменателем является число наблюдений с B."),
                    O(Pct(pBgivenA), false, "conditional_reverse", "Это P(B|A): направление условия поменяно местами."),
                    O(Pct(pA), false, "conditional_reverse", "Это безусловная вероятность A."),
                    O(Pct(pBoth), false, "conditional_reverse", "Это вероятность пересечения A∩B без нормировки на B.")
                ]);
        }

        for (var i = 1; i <= 15; i++)
        {
            var red = 5 + i % 8;
            var blue = 6 + (i * 2) % 9;
            var total = red + blue;
            var afterRed = (red - 1d) / (total - 1d);
            yield return Q(
                $"conditional_probability_large_{i + 66:000}",
                "conditional_probability",
                Difficulty(i + 66),
                i % 7 == 0,
                $"В урне {red} красных и {blue} синих шаров. Два шара вытаскивают без возвращения. Известно, что первый шар красный. Какова вероятность, что второй тоже красный?",
                $"После известного красного первого шара остаётся {red - 1} красных из {total - 1} шаров. Вероятность равна {red - 1}/{total - 1} = {Pct(afterRed)}.",
                ["conditional_reverse", "base_rate_neglect"],
                [
                    O(Pct(afterRed), true, null, "Верно: условие меняет состав оставшейся урны."),
                    O(Pct(red / (double)total), false, "base_rate_neglect", "Это вероятность красного до информации о первом вытянутом шаре."),
                    O(Pct((red - 1d) / total), false, "conditional_reverse", "После первого вытягивания меняется и числитель, и общее число шаров."),
                    O(Pct(red / (double)(total - 1)), false, "conditional_reverse", "После красного первого шара красных осталось на один меньше.")
                ]);
        }

        for (var i = 1; i <= 10; i++)
        {
            var prior = 0.12d + i * 0.025d;
            var hit = 0.68d + (i % 5) * 0.05d;
            var falseAlarm = 0.08d + (i % 4) * 0.035d;
            var posterior = prior * hit / (prior * hit + (1d - prior) * falseAlarm);
            yield return Q(
                $"conditional_probability_large_{i + 81:000}",
                "conditional_probability",
                QuestionDifficulty.Advanced,
                i % 3 == 0,
                $"Антифрод-модель проверяет транзакции. До проверки {Pct(prior)} транзакций действительно мошеннические. Модель помечает мошенническую транзакцию с вероятностью {Pct(hit)}, а обычную ошибочно помечает с вероятностью {Pct(falseAlarm)}. Транзакция помечена моделью. Как оценить вероятность мошенничества после сигнала?",
                $"Нужно пересчитать априорную вероятность по Байесу. Получаем P(мошенничество|сигнал) = {Pct(posterior)}.",
                ["base_rate_neglect", "conditional_reverse"],
                [
                    O(Pct(posterior), true, null, "Верно: это положительная прогностическая вероятность сигнала."),
                    O(Pct(hit), false, "conditional_reverse", "Это чувствительность модели, то есть P(сигнал|мошенничество)."),
                    O(Pct(prior), false, "base_rate_neglect", "Это вероятность до наблюдения сигнала."),
                    O(Pct(1d - falseAlarm), false, "base_rate_neglect", "Это специфичность, но она не является искомой вероятностью после сигнала.")
                ]);
        }
    }

    private static IEnumerable<SeedQuestionDefinition> Independence()
    {
        for (var i = 1; i <= 30; i++)
        {
            var pA = 0.20d + (i % 7) * 0.07d;
            var pB = 0.25d + (i % 6) * 0.08d;
            var product = pA * pB;
            var independent = i % 3 != 0;
            var pBoth = independent ? product : Math.Clamp(product + (i % 2 == 0 ? 0.06d : -0.05d), 0.01d, Math.Min(pA, pB));
            yield return Q(
                $"independence_large_{i:000}",
                "independence",
                Difficulty(i),
                i % 10 == 0,
                $"Даны P(A)={Pct(pA)}, P(B)={Pct(pB)} и P(A∩B)={Pct(pBoth)}. Какой вывод о независимости A и B следует из этих значений?",
                independent
                    ? $"P(A)P(B)={Pct(product)}, что совпадает с P(A∩B), поэтому события независимы."
                    : $"P(A)P(B)={Pct(product)}, что не совпадает с P(A∩B)={Pct(pBoth)}, поэтому события зависимы.",
                ["independence_vs_exclusive"],
                [
                    O(independent ? "A и B независимы" : "A и B зависимы", true, null, "Верно: проверено равенство P(A∩B)=P(A)P(B)."),
                    O(independent ? "A и B зависимы, потому что могут произойти вместе" : "A и B независимы, потому что пересечение ненулевое", false, "independence_vs_exclusive", "Совместная возможность событий не определяет независимость."),
                    O("A и B несовместны", false, "independence_vs_exclusive", "Несовместность потребовала бы P(A∩B)=0."),
                    O("По этим данным независимость проверить нельзя", false, "independence_vs_exclusive", "Для двух событий этих трёх вероятностей достаточно для проверки независимости.")
                ]);
        }

        for (var i = 1; i <= 20; i++)
        {
            var pA = 0.25d + (i % 5) * 0.09d;
            var independent = i % 2 == 0;
            var pAgivenB = independent ? pA : Math.Clamp(pA + (i % 4 - 1.5d) * 0.08d, 0.05d, 0.95d);
            yield return Q(
                $"independence_large_{i + 30:000}",
                "independence",
                Difficulty(i + 30),
                i % 8 == 0,
                $"Известно, что P(A)={Pct(pA)}, а P(A|B)={Pct(pAgivenB)}, причём P(B)>0. Что можно сказать о независимости A и B?",
                independent
                    ? "Если P(A|B)=P(A), информация о B не меняет вероятность A; для двух событий это критерий независимости."
                    : "Так как P(A|B) отличается от P(A), наступление B меняет вероятность A, следовательно события зависимы.",
                ["independence_vs_exclusive"],
                [
                    O(independent ? "Независимы" : "Зависимы", true, null, "Верно: сравниваются условная и безусловная вероятности одного и того же события."),
                    O(independent ? "Зависимы, потому что B произошло" : "Независимы, потому что P(A|B) задана", false, "independence_vs_exclusive", "Сам факт условной вероятности ничего не говорит; важно равенство P(A|B)=P(A)."),
                    O("Несовместны", false, "independence_vs_exclusive", "Несовместность — другое свойство и отсюда не следует."),
                    O("Нельзя сделать вывод", false, "independence_vs_exclusive", "При P(B)>0 сравнение P(A|B) и P(A) позволяет сделать вывод.")
                ]);
        }

        for (var i = 1; i <= 15; i++)
        {
            var scenario = i % 3;
            var prompt = scenario switch
            {
                0 => "Три честные монеты бросают независимо. События A: первая и вторая монеты совпали; B: вторая и третья совпали; C: первая и третья совпали. Они попарно независимы, но могут ли быть совместно независимыми?",
                1 => "Пусть X и Y — независимые равновероятные биты, а Z=X XOR Y. События X=1, Y=1 и Z=1 попарно независимы. Следует ли отсюда их совместная независимость?",
                _ => "В конструкции с тремя событиями каждое имеет вероятность 1/2, каждое попарное пересечение — 1/4, но тройное пересечение имеет вероятность 0. Независимы ли события совместно?"
            };
            yield return Q(
                $"independence_large_{i + 50:000}",
                "independence",
                QuestionDifficulty.Advanced,
                true,
                prompt,
                "Попарная независимость не гарантирует совместную независимость. Для совместной независимости нужно также проверять вероятности пересечений всех подмножеств, включая тройное.",
                ["independence_vs_exclusive"],
                [
                    O("Нет, попарной независимости недостаточно для совместной", true, null, "Верно: условие для тройного пересечения является дополнительным."),
                    O("Да, любая попарная независимость автоматически даёт совместную", false, "independence_vs_exclusive", "Это неверно для трёх и более событий."),
                    O("Нет, потому что независимые события обязаны быть несовместны", false, "independence_vs_exclusive", "Независимость не означает несовместность."),
                    O("Да, если у событий одинаковые вероятности", false, "independence_vs_exclusive", "Одинаковые маргинальные вероятности не заменяют условия совместной независимости.")
                ]);
        }

        for (var i = 1; i <= 16; i++)
        {
            var distribution = i % 4;
            var statement = distribution switch
            {
                0 => "X симметричен относительно нуля, а Y=X²",
                1 => "X равномерно распределён на [-1,1], а Y=|X|",
                2 => "X имеет нулевое среднее, а Y=X²-EX²",
                _ => "X принимает значения -1,0,1 симметрично, а Y=1{X=0}"
            };
            yield return Q(
                $"independence_large_{i + 65:000}",
                "independence",
                QuestionDifficulty.Advanced,
                i % 4 == 0,
                $"Рассмотрим случайные величины: {statement}. Возможно, что Corr(X,Y)=0. Какой вывод о независимости X и Y корректен?",
                "Нулевая корреляция исключает только линейную связь в соответствующем смысле. Нелинейная детерминированная зависимость может сохраняться, поэтому независимость не следует.",
                ["zero_corr_independent"],
                [
                    O("Нулевая корреляция сама по себе не доказывает независимость", true, null, "Верно: нелинейная зависимость может иметь нулевую корреляцию."),
                    O("Если корреляция равна нулю, величины обязательно независимы", false, "zero_corr_independent", "Это верно лишь в специальных классах распределений, например для совместно нормальных величин."),
                    O("Нулевая корреляция означает, что величины несовместны", false, "independence_vs_exclusive", "Несовместность относится к событиям и не является смыслом корреляции."),
                    O("Нулевая корреляция означает равенство X и Y с вероятностью 0", false, "zero_corr_independent", "Корреляция не интерпретируется таким образом.")
                ]);
        }

        for (var i = 1; i <= 10; i++)
        {
            var variant = i % 2 == 0
                ? "В общей популяции два признака независимы, но выборка оставляет только объекты, у которых выполнено хотя бы одно из двух условий."
                : "Два независимых фактора влияют на вероятность попасть в отобранную группу; анализ проводится только внутри этой группы.";
            yield return Q(
                $"independence_large_{i + 81:000}",
                "independence",
                QuestionDifficulty.Advanced,
                true,
                $"{variant} Может ли после такого отбора внутри выбранной группы появиться статистическая зависимость между факторами?",
                "Да. Условный отбор по общему следствию или критерию может создать зависимость между изначально независимыми факторами (эффект отбора/коллайдера).",
                ["zero_corr_independent", "independence_vs_exclusive"],
                [
                    O("Да, условный отбор может индуцировать зависимость", true, null, "Верно: независимость в исходной популяции не обязана сохраняться после условного отбора."),
                    O("Нет, независимость всегда сохраняется в любой подвыборке", false, "independence_vs_exclusive", "Условный отбор способен изменить структуру зависимостей."),
                    O("Да, но только если корреляция до отбора была ненулевой", false, "zero_corr_independent", "Зависимость может появиться даже при исходной независимости."),
                    O("Нет, потому что независимые факторы не могут совместно влиять на критерий отбора", false, "independence_vs_exclusive", "Независимость факторов не запрещает им оба влиять на третью переменную.")
                ]);
        }
    }

    private static IEnumerable<SeedQuestionDefinition> PValue()
    {
        for (var i = 1; i <= 26; i++)
        {
            var p = 0.004d + (i % 13) * 0.007d;
            var alpha = i % 4 == 0 ? 0.01d : 0.05d;
            var reject = p < alpha;
            yield return Q(
                $"p_value_large_{i:000}",
                "p_value",
                Difficulty(i),
                i % 10 == 0,
                $"В тесте H₀ получено p-value={p.ToString("0.000", CultureInfo.InvariantCulture)} при заранее выбранном уровне значимости α={alpha.ToString("0.00", CultureInfo.InvariantCulture)}. Какой вывод корректен?",
                reject
                    ? "При таком правиле p-value меньше α, поэтому H₀ отклоняют. Это не означает, что вероятность истинности H₀ равна p-value."
                    : "p-value не меньше α, поэтому данных недостаточно для отклонения H₀ на выбранном уровне. Это не доказывает истинность H₀.",
                ["pvalue_probability_null"],
                [
                    O(reject ? "Отклонить H₀ на выбранном уровне, не интерпретируя p-value как вероятность H₀" : "Не отклонять H₀ на выбранном уровне; это не доказывает её истинность", true, null, "Верно: решение основано на заранее выбранном α и корректной интерпретации p-value."),
                    O($"Вероятность истинности H₀ равна примерно {Pct(p)}", false, "pvalue_probability_null", "p-value — это не P(H₀|данные)."),
                    O(reject ? "Эффект обязательно большой и практически важный" : "Эффекта точно нет", false, "significance_effect", "Размер и практическая важность эффекта не определяются одним p-value."),
                    O(reject ? "Вероятность получить такой же результат в повторе равна 1-p" : "Вероятность H₁ равна 1-p", false, "pvalue_probability_null", "Такие вероятности из p-value напрямую не следуют.")
                ]);
        }

        for (var i = 1; i <= 20; i++)
        {
            var estimate = 1.5d + (i % 8) * 0.7d;
            var halfWidth = 0.8d + (i % 6) * 0.35d;
            var low = estimate - halfWidth;
            var high = estimate + halfWidth;
            var containsZero = low <= 0d && high >= 0d;
            yield return Q(
                $"p_value_large_{i + 26:000}",
                "p_value",
                Difficulty(i + 26),
                i % 7 == 0,
                $"Оценка разницы между группами равна {estimate:0.0}, а 95%-й доверительный интервал — [{low:0.0}; {high:0.0}]. Что можно сказать о двустороннем тесте нулевой разницы на уровне 5%?",
                containsZero
                    ? "Так как 0 входит в 95%-й интервал, двусторонний тест на уровне 5% не отклоняет нулевую разницу."
                    : "Так как 0 не входит в 95%-й интервал, двусторонний тест на уровне 5% отклоняет нулевую разницу.",
                ["pvalue_probability_null", "significance_effect"],
                [
