    private static SeedQuestionDefinition Q(
        string code,
        string topic,
        QuestionDifficulty difficulty,
        bool transfer,
        string prompt,
        string explanation,
        IReadOnlyList<string> misconceptions,
        IReadOnlyList<SeedOptionDefinition> options) =>
        new(
            code,
            topic,
            QuestionKind.Diagnostic,
            difficulty,
            transfer,
            prompt,
            explanation,
            misconceptions,
            options);

    private static SeedOptionDefinition O(
        string text,
        bool correct,
        string? misconception,
        string feedback) =>
        new(text, correct, misconception, feedback);

    private static QuestionDifficulty Difficulty(int index) => DifficultyProfile(index);

    private static QuestionDifficulty DifficultyProfile(int index) => (index % 10) switch
    {
        1 => QuestionDifficulty.Introductory,
        2 or 3 => QuestionDifficulty.Basic,
        4 or 5 or 6 => QuestionDifficulty.Intermediate,
        _ => QuestionDifficulty.Advanced
    };

    private static string Pct(double value) =>
        (value * 100d).ToString("0.0", CultureInfo.GetCultureInfo("ru-RU")) + "%";
